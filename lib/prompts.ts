export const buildPrompt = (input: GenerateInput) => {
  switch (input.documentType) {
    case "lesson_plan":
      return buildLessonPlanPrompt(input);
    case "worksheet":
      return buildWorksheetPrompt(input);
    case "exam":
      return buildExamPrompt(input);
    case "plc":
      return buildPLCPrompt(input);
    case "research":
      return buildResearchPrompt(input);
  }
};

