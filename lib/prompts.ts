const COMPETENCY_DETAIL = (codes: string[]) => {
  return codes
    .map((code) => {
      const c = CORE_COMPETENCIES.find((c) => c.code === code);
      return c ? `- ${c.code} ${c.name}: ${c.desc}` : "";
    })
    .filter(Boolean)
    .join("\n");
};

